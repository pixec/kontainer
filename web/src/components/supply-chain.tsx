import { useMutation, useQuery } from "@tanstack/react-query"
import { useState } from "react"
import { Link } from "react-router"
import { BadgeCheckIcon, FileTextIcon, FingerprintIcon, PackageIcon, ShieldCheckIcon } from "lucide-react"
import { Button } from "@/components/ui/button"
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog"
import { Label } from "@/components/ui/label"
import { Textarea } from "@/components/ui/textarea"
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table"
import { endpoints, formatBytes, shortDigest, type ArtifactKind, type Attached, type SignatureCheck } from "@/lib/api"
import { formatDate } from "@/lib/time"
import { ErrorBox, Loading } from "@/components/ui-bits"
import { Empty, Panel, SearchInput } from "@/components/page"
import { cn } from "@/lib/utils"

export const KIND_ICON: Partial<Record<ArtifactKind, React.ComponentType<{ className?: string }>>> = {
  signature: FingerprintIcon,
  sbom: FileTextIcon,
  attestation: BadgeCheckIcon,
  helm_chart: PackageIcon,
}

const STATUS: Record<SignatureCheck["status"], { label: string; cls: string }> = {
  verified: { label: "Verified", cls: "bg-success/10 text-success" },
  invalid: { label: "Different key", cls: "bg-destructive/10 text-destructive" },
  mismatch: { label: "Signs another image", cls: "bg-warning/10 text-warning" },
  keyless: { label: "Keyless", cls: "" },
  malformed: { label: "Malformed", cls: "bg-destructive/10 text-destructive" },
}

/** Signatures, SBOMs and attestations attached to a manifest, with viewers. */
export function SupplyChain({ name, reference, attached }: { name: string; reference: string; attached: Attached[] }) {
  const [sbom, setSbom] = useState<string | null>(null)
  const [verifying, setVerifying] = useState(false)
  const signatures = attached.filter((a) => a.kind === "signature").length
  return (
    <Panel
      icon={<ShieldCheckIcon />}
      title="Supply chain"
      actions={signatures > 0 && <Button size="sm" variant="outline" onClick={() => setVerifying(true)}><ShieldCheckIcon />Verify signature</Button>}
    >
      {attached.length === 0 ? (
        <Empty>Nothing attached. Sign with <code className="font-mono text-xs text-foreground">cosign sign</code> or attach an SBOM with <code className="font-mono text-xs text-foreground">oras attach</code>.</Empty>
      ) : (
        <ul className="divide-y">
          {attached.map((a) => {
            const Icon = KIND_ICON[a.kind] ?? FileTextIcon
            return (
              <li key={a.digest} className="flex flex-wrap items-center gap-3 px-4 py-3">
                <Icon className="size-4 shrink-0 text-muted-foreground" />
                <div className="min-w-0 flex-1">
                  <div className="text-sm font-medium">{a.label}</div>
                  <div className="truncate text-xs text-muted-foreground">
                    <span className="font-mono">{shortDigest(a.digest)}</span> · {formatBytes(a.size)} · {a.tag ? <>cosign tag <span className="font-mono">{a.tag.slice(0, 16)}...</span></> : "OCI referrer"}
                  </div>
                </div>
                {(a.kind === "sbom" || a.kind === "attestation") && <Button size="sm" variant="ghost" onClick={() => setSbom(a.digest)}>View {a.kind === "sbom" ? "SBOM" : "contents"}</Button>}
                <Button size="sm" variant="ghost" asChild><Link to={`/r/${name}/m/${a.digest}`}>Inspect</Link></Button>
              </li>
            )
          })}
        </ul>
      )}
      <SbomDialog name={name} digest={sbom} onClose={() => setSbom(null)} />
      <VerifyDialog name={name} reference={reference} open={verifying} onOpenChange={setVerifying} />
    </Panel>
  )
}

export function SbomTable({ name, digest }: { name: string; digest: string }) {
  const q = useQuery({ queryKey: ["sbom", name, digest], queryFn: () => endpoints.sbom(name, digest) })
  const [filter, setFilter] = useState("")
  if (q.isLoading) return <Loading rows={4} />
  if (q.error) return <ErrorBox error={q.error} />
  const s = q.data!.sbom
  const f = filter.toLowerCase()
  const rows = s.packages.filter((p) => !f || p.name.toLowerCase().includes(f) || (p.purl ?? "").toLowerCase().includes(f) || p.licenses.some((l) => l.toLowerCase().includes(f)))
  return (
    <div className="space-y-3">
      <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-sm text-muted-foreground">
        <span className="chip text-foreground">{s.format}{s.spec_version ? ` ${s.spec_version.replace(/^SPDX-/, "")}` : ""}</span>
        <span><b className="font-medium text-foreground tabular-nums">{s.packages.length}</b> packages</span>
        {s.tools.length > 0 && <span>Generated by {s.tools.join(", ")}</span>}
        {s.created && <span title={s.created}>{formatDate(s.created)}</span>}
      </div>
      <SearchInput placeholder="Filter packages, purls or licenses..." value={filter} onChange={setFilter} className="sm:w-full" />
      <div className="max-h-[50vh] overflow-auto rounded-lg border">
        <Table>
          <TableHeader className="sticky top-0 bg-popover"><TableRow><TableHead className="pl-4">Package</TableHead><TableHead>Version</TableHead><TableHead className="hidden md:table-cell">Type</TableHead><TableHead>License</TableHead></TableRow></TableHeader>
          <TableBody>
            {rows.length === 0 && <TableRow className="hover:bg-transparent"><TableCell colSpan={4}><Empty>No packages match.</Empty></TableCell></TableRow>}
            {rows.slice(0, 1000).map((p, i) => (
              <TableRow key={`${p.name}@${p.version}#${i}`}>
                <TableCell className="max-w-72 pl-4"><div className="truncate font-medium">{p.name}</div>{p.purl && <div className="truncate font-mono text-[11px] text-muted-foreground" title={p.purl}>{p.purl}</div>}</TableCell>
                <TableCell className="font-mono text-xs">{p.version ?? "—"}</TableCell>
                <TableCell className="hidden text-muted-foreground md:table-cell">{p.type ?? "—"}</TableCell>
                <TableCell className="text-muted-foreground">{p.licenses.join(", ") || "—"}</TableCell>
              </TableRow>
            ))}
          </TableBody>
        </Table>
      </div>
      {rows.length > 1000 && <p className="text-xs text-muted-foreground">Showing the first 1,000 of {rows.length}. Filter to narrow down.</p>}
    </div>
  )
}

function SbomDialog({ name, digest, onClose }: { name: string; digest: string | null; onClose: () => void }) {
  return (
    <Dialog open={!!digest} onOpenChange={(v) => { if (!v) onClose() }}>
      <DialogContent className="sm:max-w-4xl">
        <DialogHeader><DialogTitle>Software bill of materials</DialogTitle><DialogDescription>Packages recorded in this SBOM.</DialogDescription></DialogHeader>
        {digest && <SbomTable name={name} digest={digest} />}
      </DialogContent>
    </Dialog>
  )
}

function VerifyDialog({ name, reference, open, onOpenChange }: { name: string; reference: string; open: boolean; onOpenChange: (v: boolean) => void }) {
  const [key, setKey] = useState("")
  const verify = useMutation({ mutationFn: () => endpoints.verify(name, reference, key) })
  return (
    <Dialog open={open} onOpenChange={(v) => { onOpenChange(v); if (!v) verify.reset() }}>
      <DialogContent className="sm:max-w-xl">
        <form className="space-y-4" onSubmit={(e) => { e.preventDefault(); verify.mutate() }}>
          <DialogHeader>
            <DialogTitle>Verify signature</DialogTitle>
            <DialogDescription>Checks every cosign signature on this artifact against a public key, and that it signs this exact digest.</DialogDescription>
          </DialogHeader>
          <div className="space-y-2">
            <Label htmlFor="cosign-key">Public key (cosign.pub)</Label>
            <Textarea id="cosign-key" rows={5} className="font-mono text-xs" value={key} onChange={(e) => setKey(e.target.value)} placeholder={"-----BEGIN PUBLIC KEY-----\n...\n-----END PUBLIC KEY-----"} />
          </div>
          {verify.error && <ErrorBox error={verify.error} />}
          {verify.data && (
            <div className="space-y-2">
              <p className={cn("text-sm font-medium", verify.data.verified ? "text-success" : "text-destructive")}>{verify.data.verified ? "Verified: at least one signature matches this key." : "Not verified by this key."}</p>
              <ul className="divide-y rounded-lg border">
                {verify.data.signatures.length === 0 && <li className="px-3 py-2 text-sm text-muted-foreground">No key-based signatures found.</li>}
                {verify.data.signatures.map((s, i) => (
                  <li key={`${s.signature}-${i}`} className="flex items-center gap-3 px-3 py-2 text-sm">
                    <span className={cn("chip", STATUS[s.status].cls)}>{STATUS[s.status].label}</span>
                    <span className="min-w-0 flex-1 truncate text-muted-foreground">{s.detail}</span>
                    <span className="font-mono text-xs text-muted-foreground">{shortDigest(s.signature)}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
          <DialogFooter>
            <Button type="button" variant="outline" onClick={() => onOpenChange(false)}>Close</Button>
            <Button type="submit" disabled={!key.trim() || verify.isPending}>{verify.isPending ? "Verifying..." : "Verify"}</Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  )
}
